# Reaching this code path already means this dataset/bin had valid candidate
# pairs (collect_binned_pairs() only calls _auc_from_flat on bins with data),
# so a P<1/N<1 result here reflects this model's own failure to find matches
# in data it did have access to, not a genuine lack of underlying data.
PUNISH_MISSING_MATCHES = True


def _signed_bin_ids(delta_days):
    """
    Map signed integer day differences to a bin id: 0 for exactly same-day
    (delta_days == 0 -- also the only value landing in BIN_EDGES' first
    [0, 1) bin), and +/-k for the k-th magnitude bin in BIN_EDGES
    (BIN_EDGES[k], BIN_EDGES[k+1]) on the later/earlier side. Bins are
    therefore symmetric around 0, matching the "delta-days between this
    pair's two sessions, signed by recording order" convention used
    throughout this module (see collect_binned_pairs()).
    """
    abs_delta = np.abs(delta_days)
    mag_bin = np.clip(np.digitize(abs_delta, BIN_EDGES) - 1, 0, len(BIN_LABELS) - 1)
    return (mag_bin * np.sign(delta_days)).astype(int)


def _signed_bin_label(signed_id):
    if signed_id == 0:
        return "0"
    return ("-" if signed_id < 0 else "") + BIN_LABELS[abs(signed_id)]


N_MAG_BINS = len(BIN_LABELS)
SIGNED_BIN_ORDER = list(range(-(N_MAG_BINS - 1), N_MAG_BINS))
SIGNED_BIN_LABELS = [_signed_bin_label(s) for s in SIGNED_BIN_ORDER]


def build_session_date_lookup(base_input=BASE_INPUT, metadata_index_path=METADATA_INDEX_PATH):
    """
    For every merged-data group, reconstruct {RecSes number -> date}.

    Replicates the same good-unit selection (build_good_units_from_labels)
    and "at least one good unit's RawSpikes.npy actually exists" survival
    check that run_deepunitmatch_batch_onMerged.py's _prepare_session() /
    load_waveforms_for_good_units() use to decide which merged session
    folders get a session_id slot (and therefore a RecSes number) -- without
    loading any waveform data, same as run_emd_batch_onMerged.py's
    stage_group(). A session's numbered folder name equals its 0-based
    position in the original (pre-merge) KS_dirs list (generate_merged_dataset.py
    mirrors every KS_dirs entry, not just the ones with good units), which is
    exactly the indexing generate_metadata_index.py's exp_ids uses -- so
    folder name + 1 == the metadata index's exp_key.

    Returns {dataset_key ("mouse/probe/loc"): {recses (1-based int): date}}.
    """
    if not os.path.isfile(metadata_index_path):
        raise FileNotFoundError(
            f"metadata_index.json not found at {metadata_index_path} -- run "
            "generate_metadata_index.py against the non-merged data root first."
        )
    with open(metadata_index_path) as f:
        metadata_index = json.load(f)

    lookup = {}
    groups = base_batch.find_merged_groups()
    print(f"Reconstructing session dates for {len(groups)} group(s)...")
    for i, merged_dir in enumerate(groups):
        dataset_key = os.path.relpath(os.path.dirname(merged_dir), base_input).replace("\\", "/")
        meta = metadata_index.get(dataset_key)
        if meta is None:
            print(f"  [{i + 1}/{len(groups)}] {dataset_key}: not in metadata_index.json, skipping.")
            continue

        session_names = sorted(
            (d for d in os.listdir(merged_dir) if d.isdigit() and os.path.isdir(os.path.join(merged_dir, d))),
            key=int,
        )
        if not session_names:
            continue

        ks_dirs = [os.path.join(merged_dir, d) for d in session_names]
        try:
            wave_paths, unit_label_paths, _ = util.paths_from_KS(ks_dirs)
        except Exception as e:
            print(f"  [{i + 1}/{len(groups)}] {dataset_key}: paths_from_KS failed ({e}), skipping.")
            continue

        good_units_per_session = base_batch.build_good_units_from_labels(unit_label_paths)

        dates = meta.get("dates", {})
        recses = 0
        mapping = {}
        for folder, wave_path, g_units in zip(session_names, wave_paths, good_units_per_session):
            survives = any(
                os.path.exists(os.path.join(wave_path, f"Unit{int(uid)}_RawSpikes.npy"))
                for uid in g_units.flatten()
            )
            if not survives:
                continue
            recses += 1
            exp_key = str(int(folder) + 1)
            date_str = dates.get(exp_key)
            if date_str:
                mapping[recses] = date_str

        lookup[dataset_key] = mapping
        if (i + 1) % 25 == 0:
            print(f"  ...processed {i + 1}/{len(groups)} groups")

    return lookup


def get_session_date_lookup():
    """Load the cached session-date lookup if present, else build + cache it."""
    if os.path.isfile(SESSION_DATE_CACHE_PATH):
        print(f"Loading cached session-date lookup from {SESSION_DATE_CACHE_PATH}")
        with open(SESSION_DATE_CACHE_PATH) as f:
            raw = json.load(f)
        # JSON keys are always strings; recses needs to be int for lookups.
        return {dataset: {int(k): v for k, v in mapping.items()} for dataset, mapping in raw.items()}

    lookup = build_session_date_lookup()
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(SESSION_DATE_CACHE_PATH, "w") as f:
        json.dump(lookup, f, indent=2)
    print(f"Wrote session-date lookup cache to {SESSION_DATE_CACHE_PATH}")
    return lookup


# ── AUC over a flat (already across-session, already binned) array pair ────


def _auc_from_flat(matches_bool, metric_values, punish_missing=PUNISH_MISSING_MATCHES):
    """
    Same recall/FPR/trapezoid logic as DeepUnitMatch.testing.test.AUC(), but
    over flat arrays already restricted to across-session pairs (instead of
    an (n_units, n_units) matrix + session_id) -- so it can be reused per
    delta-days bin. Returns NaN when there are no matches or no non-matches
    to rank against (AUC() raises in the same situation) -- unless
    punish_missing is True, in which case that case returns 0.5 (chance
    level) instead. See PUNISH_MISSING_MATCHES.
    """
    P = int(matches_bool.sum())
    N = len(matches_bool) - P
    if P < 1 or N < 1:
        return 0.5 if punish_missing else np.nan
    order = np.argsort(metric_values)[::-1]
    m_sorted = matches_bool[order]
    tp = np.cumsum(m_sorted)
    fp = np.cumsum(~m_sorted)
    recall = tp / P
    fpr = fp / N
    if hasattr(np, "trapezoid"):
        return float(np.trapezoid(recall, fpr))
    return float(np.trapz(recall, fpr))


