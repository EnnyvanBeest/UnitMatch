# Companion to plot_auc_summary.py: instead of one AUC per dataset (pooling
# every across-session unit-pair together regardless of how far apart the two
# sessions were recorded), bin across-session unit-pairs by signed delta-days
# (date(RecSes 1) - date(RecSes 2)) and compute AUC per bin per score,
# pooling across every dataset -- to see whether/how tracking quality decays
# as the gap between recordings grows. Every unordered session pair already
# appears as both (i, j) and (j, i) rows in a MatchTable (see save_utils.py),
# so signed bins come out symmetric around a "0" (same-day) bin without
# needing to anchor to a per-dataset reference session.
#
# For each functional score, produces one 3-panel figure (plot_score_summary())
# styled after the paper figure this reproduces: P(track) match rate on top,
# AUC for that score in the middle, and session-pair counts on the bottom --
# one coloured line per model in every panel, all sharing the same signed
# ΔDay x-axis.
#
# AUC_summary.json (produced once per dataset/model by
# run_deepunitmatch_batch_onMerged.py / run_emd_batch_onMerged.py /
# run_dant_batch_onMerged.py) only stores the whole-dataset scalar AUC, and
# recording dates are never persisted anywhere in BASE_OUTPUT -- the merged
# tree's numbered session folders (0, 1, 2, ...) don't carry dates, and even
# the non-merged root's per-session dates (recoverable from each group's
# UMparam.pickle KS_dirs, see generate_metadata_index.py) don't map directly
# onto a MatchTable.csv's "RecSes" numbers: sessions with zero good units (or
# whose good units all lost their RawSpikes file) are silently dropped when
# run_deepunitmatch_batch_onMerged.py's _prepare_session() builds session_id,
# renumbering RecSes to skip the gaps.
#
# Rather than persisting that mapping from a pipeline run (which would need
# re-running the batch scripts), this script reconstructs it from files that
# already sit statically in the merged tree: build_session_date_lookup()
# redoes exactly the good-unit/RawSpikes-exists bookkeeping _prepare_session()
# does (the same logic run_emd_batch_onMerged.py's --stage phase already uses
# to work out good units without touching waveform data) to recover, for each
# dataset, which original KS_dirs index survived as each RecSes number -- then
# looks up that index's date in metadata_index.json. This is read-only and
# doesn't require re-running any matching.
#
# Output (plots + CSVs) is written to BASE_OUTPUT/auc_vs_delta_days_report,
# alongside plot_auc_summary.py's own auc_summary_report.

